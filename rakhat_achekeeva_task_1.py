# A coffee shop wants to apply a discount to customers who order three or more beverages.
# Your program could take the drink orders, quantity of drinks, and print a message that may or may not include a multi-item discount.

name = input('Enter your name: ')

while True:
  drink_num = input('How many drinks would you like to order? ')
  if drink_num.isalpha() or drink_num.isalnum() and not drink_num.isnumeric():
    print('Please enter valid number.')
  elif drink_num.isnumeric():
    drink_num = int(drink_num)
    break

while True:
  drink_price = int(input('Which drink price do you choose? ($3, $5, or $7): '))
  if drink_price in [3, 5, 7]:
    break
  else:
    print('Please choose from the offered prices.')
    continue

discount = 0

if drink_num < 3:
  discount = 0
elif drink_num < 6:
  discount = 0.1
else:
  discount = 0.2

total_price = drink_num * drink_price - discount * (drink_num * drink_price)

print(name + ', you ordered ' + str(drink_num) + ' drinks.')
print('Your total is $'  + str(total_price))

